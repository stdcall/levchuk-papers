"""Exact B2 checks for Levchuk, Algebra i Logika 22:5 (1983), 506–514.

We use the simply connected C2 matrix model, with a=e1-e2 short and
b=2e2 long; B2 and C2 are isomorphic as rank-two root systems. The
commutator is [x,y]=x^-1*y^-1*x*y. Signs depend on root vector choices;
the characteristic-two identities have no sign ambiguity. We check
polynomial identities, not the carpet classification or all Chevalley
groups. Passage labels are listed in the associated check registry.
"""

from sage.all import ZZ, GF, PolynomialRing, matrix, identity_matrix
from sage.env import SAGE_VERSION
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import json

checks = 0


def check(value):
    global checks
    assert value
    checks += 1


def roots(R):
    I = identity_matrix(R, 4)

    def E(i, j):
        m = matrix(R, 4)
        m[i - 1, j - 1] = 1
        return m

    A = E(1, 2) - E(4, 3)
    B = E(2, 4)
    C = E(1, 4) + E(2, 3)
    D = E(1, 3)
    return tuple(lambda t, N=N: I + t * N for N in (A, B, C, D))


def comm(x, y):
    return x.inverse() * y.inverse() * x * y


# Formula (4), printed p.507, specialized from twisted 2A3 to B2 as
# instructed at p.508 (replace conjugate(u) by u). The signs here are
# fixed by the explicitly displayed matrix generators.
R = PolynomialRing(ZZ, names=('u', 't', 'v'))
u, t, v = R.gens()
xa, xb, xc, xd = roots(R)
check(comm(xa(u), xb(t)) == xc(u*t) * xd(-u**2*t))
check(comm(xa(u), xc(v)) == xd(2*u*v))
check(comm(comm(xa(u), xb(t)), xa(u)) == xd(-2*u**2*t))

# Characteristic two: coefficient 2 vanishes identically. This tests
# exactly why this extraction cannot be used without the restriction
# on characteristic in Lemma 1 (pp.506,508).
S = PolynomialRing(GF(2), names=('u', 't', 'v'))
u, t, v = S.gens()
xa, xb, xc, xd = roots(S)
check(comm(xa(u), xc(v)) == identity_matrix(S, 4))
check(comm(xa(u), xb(t)) == xc(u*t) * xd(u**2*t))

# Concrete warning immediately after Lemma 1, p.508: the subgroup
# generated by the two simple root elements in B2(2). We enumerate
# exactly this subgroup, not arbitrary groups over other fields.
xa2, xb2, xc2, xd2 = roots(GF(2))
generators = (xa2(1), xb2(1))
subgroup = {tuple(identity_matrix(GF(2), 4).list())}
todo = [identity_matrix(GF(2), 4)]
while todo:
    element = todo.pop()
    for generator in generators:
        new = element * generator
        key = tuple(new.list())
        if key not in subgroup:
            subgroup.add(key)
            todo.append(new)
check(len(subgroup) == 8)
check(tuple(xc2(1).list()) not in subgroup)
check(tuple(xd2(1).list()) not in subgroup)
check(tuple((xc2(1) * xd2(1)).list()) in subgroup)

# Scalar part of the triality extraction, p.507. If sigma has order 3
# and fixes t, write ui=sigma^i(u). The trace expression becomes three
# equal norm monomials. This verifies the coefficient 6, not the entire
# twisted commutator formula (2).
N = PolynomialRing(ZZ, names=('u0', 'u1', 'u2', 't'))
u0, u1, u2, t0 = N.gens()
trace_term = u0*(u1*u2*t0) + u1*(u2*u0*t0) + u2*(u0*u1*t0)
check(trace_term == 3*u0*u1*u2*t0)
check(2*trace_term == 6*u0*u1*u2*t0)

# Universal rational-function identities in the exceptional B2 case,
# printed pp.513–514. All denominators below are nonzero rational
# functions; specialization requires alpha != 0.
T = PolynomialRing(GF(2), names=('alpha', 'beta', 'z'))
L = T.fraction_field()
alpha, beta, z = map(L, T.gens())
xa, xb, xc, xd = roots(L)

# B2 specializations of formula (5), for every ordered root pair.
positive = {(1,0):xa,(0,1):xb,(1,1):xc,(2,1):xd}
root_groups = dict(positive)
for rr, gen in positive.items():
    root_groups[tuple(-c for c in rr)] = lambda t, gen=gen: gen(t).transpose()
gram = matrix(ZZ,[[2,-2],[-2,4]])
def pairing(rr,ss):
    return ZZ(2*sum(rr[i]*gram[i,j]*ss[j] for i in range(2) for j in range(2))
              /sum(rr[i]*gram[i,j]*rr[j] for i in range(2) for j in range(2)))
def weyl(rr,t):
    minus_rr = tuple(-c for c in rr)
    return root_groups[rr](t)*root_groups[minus_rr](-1/t)*root_groups[rr](t)
for rr in root_groups:
    nn = weyl(rr,L(-1))
    hh = weyl(rr,z)*nn
    for ss in root_groups:
        check(hh*root_groups[ss](alpha)*hh.inverse()
              == root_groups[ss](z**pairing(rr,ss)*alpha))
        reflected = tuple(ss[i]-pairing(rr,ss)*rr[i] for i in range(2))
        # In characteristic two the Weyl sign disappears.
        check(nn*root_groups[ss](alpha)*nn.inverse()
              == root_groups[reflected](alpha))

# Section3's diagonal extractions: the unwanted short, respectively
# long, factor cancels, leaving the printed parameter sets.
hb = weyl((0,1),z)*weyl((0,1),L(-1))
ha = weyl((1,0),z)*weyl((1,0),L(-1))
ab = comm(xa(alpha),xb(beta))
check(comm(hb,ab) == xc(alpha*beta*(1-z**-1)))
check(comm(ha,ab) == xd(alpha**2*beta*(1-z**-2)))
# The lower root -a has matrix I+s(E21-E34).
I = identity_matrix(L, 4)
negA = matrix(L, 4)
negA[1, 0] = 1
negA[2, 3] = -1
xna = lambda s: I + s * negA
negB = matrix(L, 4)
negB[3, 1] = 1
xnb = lambda s: I + s * negB
check(comm(xna(alpha**2), xd(alpha**-2)) == xb(alpha**2) * xc(1))
check(comm(xc(beta**-1), xnb(beta**2)) == xa(beta) * xd(1))
# The old long-root coordinate is arbitrary, including the exceptional
# starting g0 (whose two parameters coincide). It cancels out entirely.
check(comm(comm(xc(alpha) * xd(z), xnb(beta**2)), xb(1))
      == xc(alpha*beta**2) * xd(alpha**2*beta**4))
g0 = comm(comm(xna(alpha**2), xd(alpha**-2)), xa(1))
check(g0 == xc(alpha**2) * xd(alpha**2))
gprime = comm(comm(comm(xa(1), xb(1)), xna(alpha**2)), xa(1))
check(gprime == xc(alpha**4) * xd(alpha**4))
g = xc(alpha**2) * xd(alpha**4)
check(g0 * g == xd(alpha**2 + alpha**4))
check(g * gprime == xc(alpha**2 + alpha**4))

# The second equality in the last display of p.514, after the printed
# beta^-1=alpha^-2 (hence beta=alpha^2). This checks the intermediate
# matrix commutator; its earlier replacements are not asserted here.
last = comm(xb(alpha**2) * xc(1), xa(alpha**2) * xd(1)) * gprime
candidate = xd(alpha**4 + alpha**6)
remainder = last - candidate
num_polys = [T(z.numerator()) for z in remainder.list()]
relation = T.ideal(T.gen(0)**6 + T.gen(0)**4 + 1)
check(all(relation.reduce(z) == 0 for z in num_polys))

# The final scalar argument: equality of the two values alpha^-2
# implies alpha^2*(alpha^4+1)=0, and in characteristic 2
# alpha^4+1=(alpha+1)^4. This identity is also proved in Lean.
check((alpha**2 + alpha**4) + (alpha**4 + alpha**6)
      == alpha**2 * (alpha + 1)**4)

print(f'ok l1983-root-rank-two: {checks} checks')
print(json.dumps({'sage': SAGE_VERSION,
                  'utc': datetime.now(timezone.utc).isoformat(),
                  'sha256': sha256(Path(__file__).read_bytes()).hexdigest(),
                  'checks': checks}, sort_keys=True))
